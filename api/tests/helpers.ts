export function getSessionCookie(response: InjectResponse): string {
	const setCookie = response.headers['set-cookie'];
	const cookies = setCookie == null ? [] : Array.isArray(setCookie) ? setCookie : [setCookie];
	const session = cookies.find((cookie) => cookie.startsWith('session='));

	if (session == null) throw new Error('Expected a session cookie in the response');

	return session.split(';')[0];
}

export async function getCsrf(server: FastifyInstance): Promise<{cookie: string; token: string}> {
	const response = await server.inject({method: 'GET', url: '/csrf'});
	const body = response.json() as {ok: boolean; data: {token: string}};

	if (body.ok !== true || typeof body.data.token !== 'string') {
		throw new Error('Expected a csrf token in the response');
	}

	return {cookie: getSessionCookie(response), token: body.data.token};
}

/**
 * Attempts to log in. The session cookie is only set when the login succeeds,
 * so `cookie` is undefined for failed attempts (check `response.statusCode`).
 */
export async function login(
	server: FastifyInstance,
	credentials: {email: string; password: string},
): Promise<{response: InjectResponse; cookie: string | undefined; token: string}> {
	const {cookie, token} = await getCsrf(server);
	const response = await server.inject({
		method: 'POST',
		url: '/sessions',
		headers: {cookie, 'x-csrf-token': token, 'content-type': 'application/json'},
		payload: credentials,
	});

	return {
		response,
		cookie: response.headers['set-cookie'] == null ? undefined : getSessionCookie(response),
		token,
	};
}

export function fakeBookGenre(): BookGenre {
	return faker.helpers.arrayElement(BookGenreDefinition.options);
}

// Faker's book titles come from a small pool, so make sure a test process never
// uses the same title twice (e.g. for the title__contains filter assertions).
const usedBookTitles = new Set<string>();

function fakeBookTitle(): string {
	let title = faker.book.title();

	while (usedBookTitles.has(title)) title = faker.book.title();

	usedBookTitles.add(title);

	return title;
}

export function fakeYearPublished(): number {
	return faker.number.int({min: 1900, max: new Date().getFullYear()});
}

export function fakeIsbn(): string {
	return faker.commerce.isbn();
}

export function fakePassword(): string {
	return faker.internet.password({length: 16});
}

/** Matches the ticket format generated by the api (`0000-AB12-00000000`). */
export function fakeTicket(): string {
	return `${faker.string.numeric(4)}-${faker.string.alphanumeric({length: 4, casing: 'upper'})}-${faker.string.numeric(8)}`;
}

export interface FakeBookInput {
	title: string;
	author: string;
	genre: BookGenre;
	yearPublished: number;
}

/**
 * Random book payload. Pass the cleanup prefix when the request is expected to
 * persist the book, so `deleteTestBooks` can remove it afterwards.
 */
export function fakeBookInput(prefix?: string): FakeBookInput {
	return {
		title: prefix == null ? fakeBookTitle() : `${prefix}${fakeBookTitle()}`,
		author: faker.book.author(),
		genre: fakeBookGenre(),
		yearPublished: fakeYearPublished(),
	};
}

export interface FakeMemberInput {
	externalId: string;
	name: string;
	course: string;
	yearAndSection: string;
}

/**
 * Random member payload. Pass the cleanup prefix when the request is expected
 * to persist the member, so `deleteTestMembers` can remove it afterwards.
 */
export function fakeMemberInput(prefix?: string): FakeMemberInput {
	return {
		externalId: `${prefix ?? ''}${faker.string.numeric(7)}`,
		name: faker.person.fullName(),
		course: faker.helpers.arrayElement(COURSES),
		yearAndSection: `${faker.number.int({min: 1, max: 5})}-${faker.number.int({min: 1, max: 4})}`,
	};
}

export async function createTestAccount(
	prefix: string = TEST_ACCOUNT_EMAIL_PREFIX,
): Promise<TestAccount> {
	const password = fakePassword();
	const email = `${prefix}${faker.internet.username().toLowerCase()}-${faker.string.alphanumeric({length: 8, casing: 'lower'})}@library.test`;
	const account = await prisma.account.create({
		data: {
			name: faker.person.fullName(),
			email,
			password: await hash(password, 10),
		},
		select: {id: true, name: true, email: true},
	});

	return {...account, password};
}

export async function deleteTestAccounts(
	prefix: string = TEST_ACCOUNT_EMAIL_PREFIX,
): Promise<void> {
	await prisma.account.deleteMany({
		where: {email: {startsWith: prefix}},
	});
}

